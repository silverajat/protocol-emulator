# Convert a Gowin .fs bitstream into a C header for the ESP32 JTAG loader.
# Mirrors openFPGALoader FsParser (MEM_MODE: bytes bit-reversed so they shift LSB-first in file order).
import sys
src, dst = sys.argv[1], sys.argv[2]
lines = []
for raw in open(src).read().split('\n'):
    raw = raw.rstrip('\r')
    if not raw: break
    if raw[0] == '/': continue
    lines.append(raw)
bits = ''.join(lines)
assert len(bits) % 8 == 0
data = bytes(int(bits[i:i+8][::-1], 2) for i in range(0, len(bits), 8))
# header scan
idcode = None; crc_on = False; conf_len = None; end_hdr = None; compressed = False
for i, l in enumerate(lines):
    key = int(l[:8], 2) & 0x7f; val = int(l, 2)
    if key == 0x06: idcode = val & 0xffffffff
    if key == 0x10: compressed = bool((val >> 13) & 1)
    if key == 0x3B:
        crc_on = bool((val >> 23) & 1); conf_len = val & 0xffff; end_hdr = i; break
assert idcode == 0x0000081b, hex(idcode or 0)
assert not compressed
nb = min(1342, conf_len)
cfg = lines[end_hdr + 1: end_hdr + 1 + nb]
drop = 6 * 8 + (16 if crc_on else 0)
tmp = ''.join(l[:len(l) - drop] for l in cfg)
assert len(tmp) % 16 == 0
csum = sum(int(tmp[p:p+16], 2) for p in range(0, len(tmp), 16)) & 0xffff
with open(dst, 'w') as f:
    f.write('// generated by fs2h.py from %s\n#pragma once\n#include <stdint.h>\n' % src.split('/')[-1])
    f.write('#define FPGA_BITS_LEN %d\n#define FPGA_BITS_CSUM 0x%08xu\n' % (len(data), csum))
    f.write('static const uint8_t FPGA_BITS[%d] = {\n' % len(data))
    for i in range(0, len(data), 32):
        f.write(','.join('%d' % b for b in data[i:i+32]) + ',\n')
    f.write('};\n')
print('bytes', len(data), 'checksum 0x%x' % csum, 'crc', crc_on, 'conf_len', conf_len)
