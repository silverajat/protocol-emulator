(* Protocol emulator core: the Hardcaml description of src/pe_core.v (docs/ISA.md).
   3 engines, shared program memory, pins, events, cycle counter and the register file seen by
   the host. The engines are generated by a loop over Engine.create. *)
open! Hardcaml
open Signal

let n_eng = 3
let id = 0x5045_4D55 (* "PEMU" *)
let cfg1_mask = 0x3FFF_FFFF

module I = struct
  type 'a t =
    { clk : 'a
    ; rst_n : 'a
    ; ui_in : 'a [@bits 8]
    ; uio_in : 'a [@bits 8]
    ; bus_addr : 'a [@bits 7]
    ; bus_wdata : 'a [@bits 32]
    ; bus_we : 'a
    ; bus_re : 'a
    }
  [@@deriving hardcaml]
end

module O = struct
  type 'a t =
    { uo_gp : 'a [@bits 6]
    ; uio_out : 'a [@bits 8]
    ; uio_oe : 'a [@bits 8]
    ; irq : 'a
    ; bus_rdata : 'a [@bits 32]
    }
  [@@deriving hardcaml]
end

let k w v = of_int ~width:w v

let create ?(prefix = "") (i : _ I.t) : _ O.t =
  let spec = Reg_spec.create ~clock:i.clk () in
  let nm s = prefix ^ s in
  let r w name =
    let v = Always.Variable.reg spec ~width:w in
    ignore (v.value -- nm name : Signal.t);
    v
  in
  (* ---------------- registers ---------------- *)
  let ctrl_en = r n_eng "ctrl_en" in
  let imem_ptr = r 6 "imem_ptr" in
  let pin_od = r 14 "pin_od" in
  let events = r 4 "events" in
  let time_cnt = r 32 "time_cnt" in
  let pin_val = r 14 "pin_val" in
  let pin_dir = r 8 "pin_dir" in
  let raw_in = zero 3 @: select i.ui_in 7 3 @: i.uio_in in
  let sync1 = reg spec raw_in -- nm "sync1" in
  let sync2 = reg spec sync1 -- nm "sync2" in
  let pins_in = sync2 in
  let per_eng name w = List.init n_eng (fun e -> r w (Printf.sprintf "%s_%d" name e)) in
  let cfg0 = per_eng "cfg0" 32 in
  let cfg1 = per_eng "cfg1" 32 in
  let cfg2 = per_eng "cfg2" 32 in
  let cfg3 = per_eng "cfg3" 32 in
  let poly = per_eng "poly" 32 in
  let crcw = per_eng "crcw" 5 in
  (* ---------------- host decode ---------------- *)
  let addr = i.bus_addr in
  let g_sel = select addr 6 4 ==:. 0 in
  let eng_sel = (addr >=:. 0x10) &: (addr <:. 0x10 + (8 * n_eng)) in
  let eoff = addr -:. 0x10 in
  let esel = select eoff 4 3 in
  let ereg = select eoff 2 0 in
  let greg = select addr 3 0 in
  let restart =
    mux2 (i.bus_we &: g_sel &: (greg ==:. 1)) (select i.bus_wdata (4 + n_eng - 1) 4) (zero n_eng)
  in
  (* ---------------- program memory: 64 x 16, written through IMEM_DATA ---------------- *)
  let imem_we = i.bus_we &: g_sel &: (greg ==:. 3) in
  let imem =
    List.init 64 (fun w ->
      reg spec ~enable:(imem_we &: (imem_ptr.value ==:. w)) (select i.bus_wdata 15 0)
      -- nm (Printf.sprintf "imem_%d" w))
  in
  (* ---------------- engines ---------------- *)
  let engines =
    List.init n_eng (fun e ->
      let pc = wire 6 in
      let o =
        Engine.create
          ~prefix:(Printf.sprintf "%se%d__" prefix e)
          { Engine.I.clk = i.clk
          ; rst_n = i.rst_n
          ; en = bit ctrl_en.value e
          ; restart = bit restart e
          ; cfg0 = (List.nth cfg0 e).value
          ; cfg1 = (List.nth cfg1 e).value
          ; cfg2 = (List.nth cfg2 e).value
          ; cfg3 = (List.nth cfg3 e).value
          ; crc_poly = (List.nth poly e).value
          ; crc_wm1 = (List.nth crcw e).value
          ; instr = Engine.mux_tree pc imem
          ; pins_in
          ; time_i = time_cnt.value
          ; events = events.value
          ; tx_push = i.bus_we &: eng_sel &: (esel ==:. e) &: (ereg ==:. 6)
          ; tx_din = i.bus_wdata
          ; rx_pop = i.bus_re &: eng_sel &: (esel ==:. e) &: (ereg ==:. 7)
          }
      in
      pc <== o.pc_o;
      o)
  in
  (* pin writes: the highest-numbered engine wins *)
  let pv_all, pd_all =
    List.fold_left
      (fun (pv, pd) (o : _ Engine.O.t) ->
        ( (pv &: ~:(o.pv_mask)) |: (o.pv_val &: o.pv_mask)
        , (pd &: ~:(o.pd_mask)) |: (o.pd_val &: o.pd_mask) ))
      (zero 2 @: pin_val.value, zero 8 @: pin_dir.value)
      engines
  in
  let or_all f = List.fold_left (fun acc (o : _ Engine.O.t) -> acc |: f o) (zero 4) engines in
  let evs_all = or_all (fun o -> o.ev_set) in
  let evc_all = or_all (fun o -> o.ev_clr) in
  (* ---------------- outputs ---------------- *)
  let pv = pin_val.value in
  let od = pin_od.value in
  let uio_out = concat_lsb (List.init 8 (fun p -> mux2 (bit od p) gnd (bit pv p))) in
  let uio_oe =
    concat_lsb (List.init 8 (fun p -> mux2 (bit od p) ~:(bit pv p) (bit pin_dir.value p)))
  in
  (* ---------------- host read mux ---------------- *)
  let status =
    concat_lsb
      (List.map (fun (o : _ Engine.O.t) -> concat_msb [ o.tx_full; o.tx_empty; o.rx_full; o.rx_empty ]) engines)
  in
  let pcs = concat_lsb (List.map (fun (o : _ Engine.O.t) -> o.pc_o) engines) in
  let g_rdata =
    mux
      greg
      [ k 32 id
      ; uresize ctrl_en.value 32
      ; uresize imem_ptr.value 32
      ; zero 32
      ; uresize status 32
      ; time_cnt.value
      ; uresize pin_od.value 32
      ; uresize events.value 32
      ; zero 2 @: pin_val.value @: pins_in
      ; uresize pcs 32
      ; zero 32
      ]
  in
  (* configuration and program memory are write-only (the host keeps its own copy) *)
  let rx_empty_sel = mux esel (List.map (fun (o : _ Engine.O.t) -> o.rx_empty) engines) in
  let rx_head_sel = mux esel (List.map (fun (o : _ Engine.O.t) -> o.rx_head) engines) in
  let e_rdata = mux2 ((ereg ==:. 7) &: ~:rx_empty_sel) rx_head_sel (zero 32) in
  let bus_rdata = mux2 g_sel g_rdata (mux2 eng_sel e_rdata (zero 32)) in
  (* ---------------- sequential ---------------- *)
  let eng_write e = i.bus_we &: eng_sel &: (esel ==:. e) in
  Always.(
    compile
      [ if_
          ~:(i.rst_n)
          ([ ctrl_en <-- zero n_eng
           ; imem_ptr <-- zero 6
           ; pin_od <-- zero 14
           ; events <-- zero 4
           ; time_cnt <-- zero 32
           ; pin_val <-- k 14 0x3FFF (* outputs idle high; open-drain pins released *)
           ; pin_dir <-- zero 8
           ]
           @ List.concat
               (List.init n_eng (fun e ->
                  [ List.nth cfg0 e <-- k 32 (63 lsl 22)
                  ; List.nth cfg1 e <-- zero 32
                  ; List.nth cfg2 e <-- zero 32
                  ; List.nth cfg3 e <-- zero 32
                  ; List.nth poly e <-- zero 32
                  ; List.nth crcw e <-- zero 5
                  ])))
          ([ time_cnt <-- time_cnt.value +:. 1
           ; pin_val <-- select pv_all 13 0
           ; pin_dir <-- select pd_all 7 0
           ; events <-- ((events.value &: ~:evc_all) |: evs_all)
           ; when_
               (i.bus_we &: g_sel)
               [ switch
                   greg
                   [ k 4 1, [ ctrl_en <-- select i.bus_wdata (n_eng - 1) 0 ]
                   ; k 4 2, [ imem_ptr <-- select i.bus_wdata 5 0 ]
                   ; k 4 3, [ imem_ptr <-- imem_ptr.value +:. 1 ]
                   ; k 4 6, [ pin_od <-- select i.bus_wdata 13 0 ]
                   ; k 4 7, [ events <-- select i.bus_wdata 3 0 ]
                   ]
               ]
           ]
           @ List.init n_eng (fun e ->
             when_
               (eng_write e)
               [ switch
                   ereg
                   [ k 3 0, [ List.nth cfg0 e <-- i.bus_wdata ]
                   ; k 3 1, [ List.nth cfg1 e <-- (i.bus_wdata &: k 32 cfg1_mask) ]
                   ; k 3 2, [ List.nth cfg2 e <-- i.bus_wdata ]
                   ; k 3 3, [ List.nth cfg3 e <-- i.bus_wdata ]
                   ; k 3 4, [ List.nth poly e <-- i.bus_wdata ]
                   ; k 3 5, [ List.nth crcw e <-- select i.bus_wdata 4 0 ]
                   ]
               ]))
      ]);
  { O.uo_gp = select pv 13 8; uio_out; uio_oe; irq = bit events.value 3; bus_rdata }
;;
